package sqldb

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// TestBunBoundary_NoUnsafe keeps the package on Bun's public API: no non-test
// file imports unsafe, so nothing reads or writes Bun's private fields and a
// Bun upgrade is checked by the count conformance suite, not by a layout.
func TestBunBoundary_NoUnsafe(t *testing.T) {
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(".", name), nil, parser.ImportsOnly)
		if err != nil {
			t.Fatalf("parse %s: %v", name, err)
		}
		for _, imp := range f.Imports {
			path, err := strconv.Unquote(imp.Path.Value)
			if err != nil {
				t.Fatalf("%s: unquote import %s: %v", name, imp.Path.Value, err)
			}
			if path == "unsafe" {
				t.Errorf("%s imports unsafe; sqldb uses Bun's public API only", name)
			}
		}
	}
}
